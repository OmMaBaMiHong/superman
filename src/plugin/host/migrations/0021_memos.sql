-- 0021_memos —— 随记/计划（flomo 式随手记 + 日历规划）：
-- note=随记（created_at 即记忆锚点）| plan=计划（due_at 落日历，先只标记不推送）。
-- 可关联收藏（article_id）；正文 #标签 自动解析入库 tags。
create table if not exists memos (
  id         bigint generated by default as identity primary key,
  user_id    bigint      not null references users(id) on delete cascade,
  kind       text        not null default 'note',
  content    text        not null default '',
  tags       text[]      not null default '{}',
  article_id bigint      null references articles(id) on delete set null,
  due_at     timestamptz null,
  done_at    timestamptz null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint memos_kind_check check (kind in ('note', 'plan'))
);
create index if not exists memos_user_created_idx on memos (user_id, created_at desc);
create index if not exists memos_user_due_idx on memos (user_id, due_at);

