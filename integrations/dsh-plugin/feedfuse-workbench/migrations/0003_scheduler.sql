-- 0003_scheduler.sql —— 调度器日志 + 配置（全新表）

CREATE TABLE IF NOT EXISTS scheduler_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_type TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'running',
  triggered_by TEXT NOT NULL DEFAULT 'scheduler',
  total_count INT DEFAULT 0,
  succeeded_count INT DEFAULT 0,
  failed_count INT DEFAULT 0,
  skipped_count INT DEFAULT 0,
  details JSONB,
  error_message TEXT,
  started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  finished_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS scheduler_runs_type_idx ON scheduler_runs(job_type, started_at DESC);
CREATE INDEX IF NOT EXISTS scheduler_runs_status_idx ON scheduler_runs(status);

CREATE TABLE IF NOT EXISTS scheduler_config (
  key TEXT PRIMARY KEY,
  value JSONB NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
